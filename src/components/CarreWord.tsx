import { useEffect, useId, useState, type CSSProperties } from 'react'
import { carreStrokes, type PenStroke, type WordStrokes } from '../lib/carreStrokes'

// The name of the app on the login, written the way an iPhone says hello, STROKE BY STROKE: "CarreApp" is written by a pen in eight
// typefaces and scripts (Latin, Japanese, Arabic, Devanagari, Korean, Chinese), each one from the side it starts on, and it ends on the
// real logotype, which stays. It sits where the name always was, next to the crest, and nothing waits for it: the form is usable at once.
//
// How: lib/carreStrokes.ts (generated by tools/carre-strokes) has, for every word, its outline and the centre line of its letters as pen
// paths. Each path is drawn with a thick round pen (stroke-dashoffset) and clipped by the outline, so the letters appear exactly as the
// typeface draws them, written along their own shape. At the end of every word the plain outline fades in over the pen, so nothing is
// ever left half written.
export const WORDS: WordStrokes[] = carreStrokes.words

export const START_MS = 450 // a breath before the first one
export const WRITE_MS = 640 // the pen writes one spelling
export const STEP_MS = 900 // one spelling on screen: writing, a pause, and leaving
export const LOGO_WRITE_MS = 1100 // the pen writes the logotype
const LEAVE_MS = 140

/** Shares the writing time among the strokes by their length; each starts a little before the previous one ends. The whole never lasts longer than `total`. */
export function schedule(strokes: PenStroke[], total: number): { delay: number; dur: number }[] {
  const sum = strokes.reduce((n, s) => n + s.len, 0) || 1
  let t = 0
  const raw = strokes.map((s) => {
    const dur = Math.max(60, (s.len / sum) * total) // even a dot gets a moment
    const at = t
    t += dur * 0.9
    return { at, dur }
  })
  const end = Math.max(...raw.map((r) => r.at + r.dur))
  const k = end > total ? total / end : 1
  return raw.map((r) => ({ delay: Math.round(r.at * k), dur: Math.max(1, Math.round(r.dur * k)) }))
}

function Pens({ strokes, total }: { strokes: PenStroke[]; total: number }) {
  const times = schedule(strokes, total)
  return (
    <>
      {strokes.map((s, i) => (
        <path
          key={i}
          d={s.d}
          pathLength={1}
          strokeWidth={s.w}
          className="cw-pen"
          style={{ '--delay': `${times[i].delay}ms`, '--dur': `${times[i].dur}ms` } as CSSProperties}
        />
      ))}
    </>
  )
}

function Spelling({ word }: { word: WordStrokes }) {
  const clip = `cw-${useId().replace(/:/g, '')}`
  const times = schedule(word.strokes, WRITE_MS)
  const written = Math.max(...times.map((t) => t.delay + t.dur))
  return (
    <span className={`cw-word${word.gold ? ' gold' : ''}`} lang={word.lang} aria-hidden="true" style={{ '--leave': `${STEP_MS - LEAVE_MS}ms` } as CSSProperties}>
      <svg viewBox={word.viewBox} preserveAspectRatio="xMinYMid meet">
        <defs>
          <clipPath id={clip}>
            <path d={word.outline} />
          </clipPath>
        </defs>
        <g clipPath={`url(#${clip})`}>
          <Pens strokes={word.strokes} total={WRITE_MS} />
        </g>
        <path d={word.outline} className="cw-fill" style={{ '--delay': `${written}ms` } as CSSProperties} />
      </svg>
    </span>
  )
}

// The logotype is the plain brand file (/wordmark.svg) used as a mask: the pen is drawn inside, so only the logotype shows.
function Logotype() {
  const [x, y, w, h] = carreStrokes.final.viewBox.split(' ').map(Number)
  const times = schedule(carreStrokes.final.strokes, LOGO_WRITE_MS)
  const written = Math.max(...times.map((t) => t.delay + t.dur))
  return (
    <span className="cw-logo" aria-hidden="true">
      <svg viewBox={`${x} ${y} ${w} ${h}`} preserveAspectRatio="xMinYMid meet">
        <Pens strokes={carreStrokes.final.strokes} total={LOGO_WRITE_MS} />
        <rect x={x} y={y} width={w} height={h} className="cw-fill" style={{ '--delay': `${written}ms` } as CSSProperties} />
      </svg>
    </span>
  )
}

export default function CarreWord() {
  const reduced = typeof window !== 'undefined' && window.matchMedia?.('(prefers-reduced-motion: reduce)').matches
  const [step, setStep] = useState(reduced ? WORDS.length : -1) // WORDS.length = the logotype, where it stays
  const done = step >= WORDS.length

  useEffect(() => {
    if (done) return
    const t = window.setTimeout(() => setStep((s) => s + 1), step < 0 ? START_MS : STEP_MS)
    return () => window.clearTimeout(t)
  }, [step, done])

  return (
    <span className={`cw${done ? ' is-final' : ''}`} aria-hidden="true">
      {step >= 0 && !done && <Spelling key={step} word={WORDS[step]} />}
      {done && <Logotype />}
    </span>
  )
}
